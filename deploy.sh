#!/usr/bin/env bash
#
# Deploy the inventory-export-lambda CloudFormation stack and push the real
# handler code from src/handler.py.
#
# This performs the full two-step deploy described in the README:
#   1. aws cloudformation deploy  (Lambda + IAM role + S3 bucket)
#   2. aws lambda update-function-code  (replace placeholder with real code)
#
# Usage:
#   ./deploy.sh [options]
#
# Options:
#   -b, --bucket NAME        S3 bucket name for inventory CSVs.
#                            Omit to let CloudFormation generate a unique name.
#   -s, --stack-name NAME    CloudFormation stack name.
#                            (default: inventory-export-lambda)
#   -f, --function-name NAME Lambda function name.
#                            (default: inventory-export-lambda)
#   -q, --query STRING       Resource Explorer query string. (default: *)
#   -r, --region REGION      AWS region. (default: current CLI/env region)
#   -p, --profile NAME       AWS CLI profile to use.
#       --skip-code          Deploy the stack only; do not push handler code.
#   -h, --help               Show this help and exit.
#
# Examples:
#   ./deploy.sh --bucket my-inventory-bucket
#   ./deploy.sh -b my-inventory-bucket -r us-east-1 -p my-profile
#   ./deploy.sh                       # auto-generated bucket name

set -euo pipefail

# ---- Defaults ---------------------------------------------------------------
STACK_NAME="inventory-export-lambda"
FUNCTION_NAME="inventory-export-lambda"
BUCKET_NAME=""
RESOURCE_QUERY="*"
REGION="us-east-1"
PROFILE=""
SKIP_CODE="false"

# Resolve paths relative to this script so it works from any directory.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TEMPLATE_FILE="${SCRIPT_DIR}/template.yaml"
SRC_DIR="${SCRIPT_DIR}/src"

# ---- Helpers ----------------------------------------------------------------
usage() {
  sed -n '2,29p' "${BASH_SOURCE[0]}" | sed 's/^#//; s/^ //'
}

die() {
  echo "error: $*" >&2
  exit 1
}

# ---- Parse arguments --------------------------------------------------------
while [[ $# -gt 0 ]]; do
  case "$1" in
    -b|--bucket)        BUCKET_NAME="${2:-}"; shift 2 ;;
    -s|--stack-name)    STACK_NAME="${2:-}"; shift 2 ;;
    -f|--function-name) FUNCTION_NAME="${2:-}"; shift 2 ;;
    -q|--query)         RESOURCE_QUERY="${2:-}"; shift 2 ;;
    -r|--region)        REGION="${2:-}"; shift 2 ;;
    -p|--profile)       PROFILE="${2:-}"; shift 2 ;;
    --skip-code)        SKIP_CODE="true"; shift ;;
    -h|--help)          usage; exit 0 ;;
    *)                  die "unknown option: $1 (use --help)" ;;
  esac
done

# ---- Preconditions ----------------------------------------------------------
command -v aws >/dev/null 2>&1 || die "aws CLI not found on PATH."
command -v zip >/dev/null 2>&1 || die "zip not found on PATH."
[[ -f "${TEMPLATE_FILE}" ]] || die "template not found: ${TEMPLATE_FILE}"
[[ -f "${SRC_DIR}/handler.py" ]] || die "handler not found: ${SRC_DIR}/handler.py"

# Build common AWS CLI args (region/profile) once.
AWS_ARGS=()
[[ -n "${REGION}"  ]] && AWS_ARGS+=(--region "${REGION}")
[[ -n "${PROFILE}" ]] && AWS_ARGS+=(--profile "${PROFILE}")

# ---- Step 1: deploy the stack ----------------------------------------------
echo ">> Deploying stack '${STACK_NAME}'..."
if [[ -n "${BUCKET_NAME}" ]]; then
  echo "   bucket name: ${BUCKET_NAME}"
else
  echo "   bucket name: (auto-generated by CloudFormation)"
fi

aws cloudformation deploy \
  --template-file "${TEMPLATE_FILE}" \
  --stack-name "${STACK_NAME}" \
  --capabilities CAPABILITY_IAM \
  --parameter-overrides \
      "FunctionName=${FUNCTION_NAME}" \
      "BucketName=${BUCKET_NAME}" \
      "ResourceQuery=${RESOURCE_QUERY}" \
  ${AWS_ARGS[@]+"${AWS_ARGS[@]}"}

# ---- Step 2: push the real handler code -------------------------------------
if [[ "${SKIP_CODE}" == "true" ]]; then
  echo ">> --skip-code set; leaving placeholder code in place."
else
  echo ">> Packaging and uploading handler code..."
  # Use a temp directory and write a fresh archive inside it. zip refuses to
  # add entries to an existing (empty) file, so we must not pre-create the zip.
  TMP_DIR="$(mktemp -d -t inventory-function)"
  trap 'rm -rf "${TMP_DIR}"' EXIT
  ZIP_FILE="${TMP_DIR}/function.zip"

  # zip from inside src/ so handler.py sits at the archive root (handler.lambda_handler).
  ( cd "${SRC_DIR}" && zip -q -j "${ZIP_FILE}" handler.py )

  aws lambda update-function-code \
    --function-name "${FUNCTION_NAME}" \
    --zip-file "fileb://${ZIP_FILE}" \
    --publish \
    ${AWS_ARGS[@]+"${AWS_ARGS[@]}"} \
    >/dev/null

  echo "   code uploaded to function '${FUNCTION_NAME}'."
fi

# ---- Report stack outputs ---------------------------------------------------
echo ">> Stack outputs:"
aws cloudformation describe-stacks \
  --stack-name "${STACK_NAME}" \
  --query "Stacks[0].Outputs[].{Key:OutputKey,Value:OutputValue}" \
  --output table \
  ${AWS_ARGS[@]+"${AWS_ARGS[@]}"}

echo ">> Done."
